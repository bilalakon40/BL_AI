# التمرين 01: بطاقة هوية بسيطة

# المطلوب: اكتب برنامج يطبع بطاقة هوية تحتوي على:
# - اسمك
# - عمرك  
# - مدينتك
# - مهنتك (أو طالب)
# - هوايتك المفضلة

# مثال للناتج المتوقع:
# ╔══════════════════════════╗
# ║     بطاقة الهوية         ║
# ╠══════════════════════════╣
# ║ الاسم: ......            ║
# ║ العمر: ......            ║
# ║ المدينة: ......          ║
# ║ المهنة: ......           ║
# ║ الهواية: ......          ║
# ╚══════════════════════════╝

# اكتب الكود أدناه:
name = "بلال"
age = 25
city = "ليبيا"
job = "مبرمج"
hobby = "AI"

print("╔══════════════════════════╗")
print("║     بطاقة الهوية         ║")
print("╠══════════════════════════╣")
print(f"║ الاسم: {name:<16}  ║")
print(f"║ العمر: {age:<16}  ║")
print(f"║ المدينة: {city:<14}  ║")
print(f"║ المهنة: {job:<14}  ║")
print(f"║ الهواية: {hobby:<14}  ║")
print("╚══════════════════════════╝")
